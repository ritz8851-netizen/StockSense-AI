/**
 * Generates realistic 90 days of sales transactions with weekday/weekend curves and occasional promotions.
 */
export function generateDemoSales(): SaleRecord[] {
  const sales: SaleRecord[] = [];
  const channels: Array<'In-Store' | 'Online' | 'Wholesale'> = ['In-Store', 'In-Store', 'In-Store', 'Online', 'Wholesale'];
  const today = new Date();

  INITIAL_PRODUCTS.forEach((product) => {
    // Generate sales for the past 90 days
    for (let i = 90; i >= 1; i--) {
      const d = new Date(today);
      d.setDate(d.getDate() - i);
      const dateStr = d.toISOString().split('T')[0];
      const dayOfWeek = d.getDay(); // 0 is Sunday, 6 is Saturday

      // Weekend multiplier (Friday, Saturday, Sunday have 30-50% higher grocery footfall)
      let dayMultiplier = 1.0;
      if (dayOfWeek === 0 || dayOfWeek === 6) dayMultiplier = 1.45;
      if (dayOfWeek === 5) dayMultiplier = 1.25;

      // Deterministic pseudorandom based on date and product id
      const seed = (d.getTime() % 1000) + (product.sku.charCodeAt(3) * 17);
      const variance = ((seed % 100) / 100) * 0.8 + 0.6; // 0.6 to 1.4

      let qty = Math.round(product.avgDailySales * dayMultiplier * variance);

      // On some days 0 sales for low moving items
      if (product.avgDailySales < 1.5 && (seed % 3 === 0)) {
        qty = 0;
      }

      // If out of stock recently, sales drop to 0 in last 3 days
      if (product.currentStock === 0 && i <= 3) {
        qty = 0;
      }

      if (qty > 0) {
        const channel = channels[seed % channels.length];
        const revenue = qty * product.sellingPrice;
        sales.push({
          id: `sale_${product.id}_${i}`,
          productId: product.id,
          sku: product.sku,
          productName: product.name,
          quantity: qty,
          sellingPrice: product.sellingPrice,
          costPrice: product.purchaseCost,
          totalRevenue: revenue,
          date: dateStr,
          channel,
        });
      }
    }
  });

  return sales;
}

